-- ==============================================================================
-- 3. TABLA: perfil_guias (Especializada para Guías de Turismo)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.perfil_guias (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre_completo VARCHAR(150) NOT NULL,
    tarjeta_profesional VARCHAR(50) NOT NULL UNIQUE,
    telefono_principal VARCHAR(20) NOT NULL,
    tiene_whatsapp BOOLEAN DEFAULT TRUE,
    telefono_alternativo VARCHAR(20) NULL,
    contacto_emergencia_nombre VARCHAR(100) NOT NULL,
    contacto_emergencia_tel VARCHAR(20) NOT NULL,
    reseña_corta VARCHAR(300) NOT NULL,
    experiencia_detalle TEXT NOT NULL,
    competencias_tec TEXT NULL,
    idiomas VARCHAR(200) NOT NULL DEFAULT 'Español',
    url_foto_rostro TEXT NULL,
    url_rnt TEXT NULL,
    url_tarjeta_profesional TEXT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente', -- 'pendiente', 'activo', 'rechazado'
    motivo_rechazo TEXT NULL,
    creado_en TIMESTAMPTZ DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 4. TABLA: guia_especialidades (Tabla Pivote / Relación Muchos a Muchos)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.guia_especialidades (
    guia_id INT NOT NULL REFERENCES public.perfil_guias(id) ON DELETE CASCADE,
    especialidad_id INT NOT NULL REFERENCES public.especialidades(id) ON DELETE CASCADE,
    asignado_en TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (guia_id, especialidad_id)
);

-- ==============================================================================
-- 5. TABLA: paquetes_tours (Productos Turísticos Creados por Agencias)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.paquetes_tours (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agencia_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre_tour VARCHAR(200) NOT NULL,
    descripcion TEXT NOT NULL,
    duracion_horas INT NOT NULL,
    precio NUMERIC(12,2) NOT NULL DEFAULT 0,
    cupos_totales INT NOT NULL DEFAULT 15,
    ubicacion VARCHAR(150) NOT NULL DEFAULT 'Bogotá D.C.',
    nivel_dificultad VARCHAR(50) NOT NULL DEFAULT 'Baja',
    punto_encuentro TEXT NULL,
    que_incluye TEXT NULL,
    recomendaciones TEXT NULL,
    imagenes TEXT[] DEFAULT '{}',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 6. TABLA: tour_especialidades (Pivote para el Matching con Perfiles de Guía)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.tour_especialidades (
    tour_id INT NOT NULL REFERENCES public.paquetes_tours(id) ON DELETE CASCADE,
    especialidad_id INT NOT NULL REFERENCES public.especialidades(id) ON DELETE CASCADE,
    agregado_en TIMESTAMPTZ DEFAULT NOW(),
    PRIMARY KEY (tour_id, especialidad_id)
);

-- ==============================================================================
-- 7. TABLA: programacion_tours (Salidas y Horarios con Control de Cupos)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.programacion_tours (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id INT NOT NULL REFERENCES public.paquetes_tours(id) ON DELETE CASCADE,
    guia_id INT NULL REFERENCES public.perfil_guias(id) ON DELETE SET NULL,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    cupos_maximos INT NOT NULL,
    cupos_disponibles INT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Disponible', -- 'Disponible', 'Completo', 'Cancelado'
    creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- Índices para optimizar consultas de reservas y matching
CREATE INDEX IF NOT EXISTS idx_programacion_tour_fecha ON public.programacion_tours (tour_id, fecha, estado);
CREATE INDEX IF NOT EXISTS idx_guia_especialidades_guia ON public.guia_especialidades (guia_id);
CREATE INDEX IF NOT EXISTS idx_tour_especialidades_tour ON public.tour_especialidades (tour_id);

-- ==============================================================================
-- 8. MIGRACIÓN DE DATOS PREEXISTENTES (Si ya existen guías en la tabla `perfiles`)
-- ==============================================================================
-- Copia a los guías que ya estaban registrados en `perfiles` hacia `perfil_guias`
INSERT INTO public.perfil_guias (
    usuario_id,
    nombre_completo,
    tarjeta_profesional,
    telefono_principal,
    tiene_whatsapp,
    telefono_alternativo,
    contacto_emergencia_nombre,
    contacto_emergencia_tel,
    reseña_corta,
    experiencia_detalle,
    competencias_tec,
    idiomas,
    estado
)
SELECT 
    p.id AS usuario_id,
    COALESCE(p.nombre_completo, 'Guía Profesional') AS nombre_completo,
    COALESCE(p.numero_rnt, 'RNT-' || SUBSTRING(p.id::text, 1, 6)) AS tarjeta_profesional,
    '+573000000000' AS telefono_principal,
    TRUE AS tiene_whatsapp,
    NULL AS telefono_alternativo,
    'Contacto de Emergencia' AS contacto_emergencia_nombre,
    '+573000000000' AS contacto_emergencia_tel,
    'Guía profesional de turismo certificado para recorridos en Bogotá.' AS reseña_corta,
    'Experiencia guiando turistas nacionales e internacionales en Bogotá.' AS experiencia_detalle,
    'Primeros auxilios básicos' AS competencias_tec,
    COALESCE(p.idiomas, 'Español') AS idiomas,
    COALESCE(p.estado::text, 'aprobado') AS estado
FROM public.perfiles p
WHERE p.rol = 'guia'
ON CONFLICT (usuario_id) DO NOTHING;

-- Copia paquetes turísticos antiguos a `paquetes_tours` si existe la tabla `paquetes`
DO $$
BEGIN
    IF EXISTS (SELECT FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'paquetes') THEN
        INSERT INTO public.paquetes_tours (
            agencia_id,
            nombre_tour,
            descripcion,
            duracion_horas,
            precio,
            cupos_totales,
            ubicacion,
            nivel_dificultad,
            punto_encuentro,
            que_incluye,
            recomendaciones,
            imagenes,
            activo
        )
        SELECT 
            p.agencia_id,
            p.nombre AS nombre_tour,
            p.descripcion,
            COALESCE(p.duracion_horas, 4) AS duracion_horas,
            COALESCE(p.precio, 0) AS precio,
            COALESCE(p.cupos_maximos, p.cupos_totales, 15) AS cupos_totales,
            COALESCE(p.ubicacion, 'Bogotá D.C.') AS ubicacion,
            COALESCE(p.nivel_dificultad, 'Baja') AS nivel_dificultad,
            p.punto_encuentro,
            p.incluye AS que_incluye,
            p.recomendaciones,
            COALESCE(p.imagenes, '{}'),
            COALESCE(p.activo, TRUE)
        FROM public.paquetes p
        ON CONFLICT DO NOTHING;
    END IF;
END $$;

