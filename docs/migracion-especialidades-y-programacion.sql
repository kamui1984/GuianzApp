-- 9. POLÍTICAS DE ACCESO (ROW LEVEL SECURITY - RLS)
-- ==============================================================================
ALTER TABLE public.especialidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.perfil_guias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.guia_especialidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paquetes_tours ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tour_especialidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.programacion_tours ENABLE ROW LEVEL SECURITY;

-- especialidades: lectura pública para todos los usuarios
CREATE POLICY "Especialidades lectura pública" 
ON public.especialidades FOR SELECT USING (true);

-- perfil_guias: lectura pública para guías aprobados, edición propia o de admin
CREATE POLICY "Perfil guías lectura pública de aprobados" 
ON public.perfil_guias FOR SELECT USING (estado::text = 'aprobado' OR auth.uid() = usuario_id);

CREATE POLICY "Guía edita su propio perfil" 
ON public.perfil_guias FOR UPDATE USING (auth.uid() = usuario_id);

CREATE POLICY "Guía inserta su propio perfil" 
ON public.perfil_guias FOR INSERT WITH CHECK (auth.uid() = usuario_id);

-- guia_especialidades: lectura pública, modificación por el guía
CREATE POLICY "Guía especialidades lectura pública" 
ON public.guia_especialidades FOR SELECT USING (true);

-- paquetes_tours: lectura pública de activos, gestión por agencia creadora
CREATE POLICY "Paquetes lectura pública de activos" 
ON public.paquetes_tours FOR SELECT USING (activo = true OR auth.uid() = agencia_id);

CREATE POLICY "Agencia gestiona sus propios paquetes" 
ON public.paquetes_tours FOR ALL USING (auth.uid() = agencia_id);

-- tour_especialidades y programacion_tours: lectura pública
CREATE POLICY "Tour especialidades lectura pública" 
ON public.tour_especialidades FOR SELECT USING (true);

CREATE POLICY "Programación tours lectura pública" 
ON public.programacion_tours FOR SELECT USING (true);

